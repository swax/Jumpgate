import { getState, setLocked, setSelectedNodeIds } from "./state";

const UNLOCK_SVG = `<svg viewBox="0 0 24 24" fill="currentColor"><path d="M12 17c1.1 0 2-.9 2-2s-.9-2-2-2-2 .9-2 2 .9 2 2 2zm6-9h-1V6c0-2.76-2.24-5-5-5S7 3.24 7 6h2c0-1.66 1.34-3 3-3s3 1.34 3 3v2H6c-1.1 0-2 .9-2 2v10c0 1.1.9 2 2 2h12c1.1 0 2-.9 2-2V10c0-1.1-.9-2-2-2z"/></svg>`;
const LOCK_SVG = `<svg viewBox="0 0 24 24" fill="currentColor"><path d="M18 8h-1V6c0-2.76-2.24-5-5-5S7 3.24 7 6v2H6c-1.1 0-2 .9-2 2v10c0 1.1.9 2 2 2h12c1.1 0 2-.9 2-2V10c0-1.1-.9-2-2-2zm-6 9c-1.1 0-2-.9-2-2s.9-2 2-2 2 .9 2 2-.9 2-2 2zM9 8V6c0-1.66 1.34-3 3-3s3 1.34 3 3v2H9z"/></svg>`;

export function setupLockToggle(button: HTMLButtonElement): void {
  button.innerHTML = UNLOCK_SVG;
  button.addEventListener("click", () => {
    const newLocked = !getState().locked;
    setLocked(newLocked);
    if (newLocked) {
      setSelectedNodeIds([]);
    }
    button.innerHTML = newLocked ? LOCK_SVG : UNLOCK_SVG;
    button.title = newLocked ? "Unlock editing" : "Lock editing";
  });
}
